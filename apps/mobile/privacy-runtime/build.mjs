import { build } from 'vite';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const require = createRequire(resolve(root, 'apps/extension/package.json'));
const wasm = (await import(require.resolve('vite-plugin-wasm'))).default;
const result = await build({ configFile: false, logLevel: 'warn', define: { 'process.env.NODE_ENV': '"production"' }, plugins: [wasm()], resolve: { alias: {
  '@grape/core': resolve(root, 'packages/core/src/index.ts'),
  '@grape/solana/privacy': resolve(root, 'packages/solana/src/privacy.ts'),
} }, build: { write: false, target: 'esnext', minify: true, lib: { entry: resolve(root, 'apps/mobile/privacy-runtime/index.ts'), name: 'GrapePrivacyRuntime', formats: ['iife'] }, rollupOptions: { output: { inlineDynamicImports: true } } } });
const output = (Array.isArray(result) ? result[0] : result).output;
if (output.some(item => item.type === 'asset')) throw new Error('Privacy runtime must be entirely bundled.');
const code = output.find(item => item.type === 'chunk').code.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' 'wasm-unsafe-eval'; connect-src https:; img-src data:; base-uri 'none'; form-action 'none'"></head><body><script>globalThis.process={env:{NODE_ENV:"production"},browser:true};${code}</script></body></html>`;
const destination = resolve(root, 'apps/mobile/src/generated');
await mkdir(destination, { recursive: true });
await writeFile(resolve(destination, 'privacyRuntime.ts'), `// Generated by privacy-runtime/build.mjs. Do not edit.\nexport const privacyRuntimeHtml = ${JSON.stringify(html)};\n`);
console.log('Bundled local privacy runtime.');
